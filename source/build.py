def tighten(src):
    punct = set('{}()[],;'); re_prev = set('([{:;,=!?&|~^%+-<>')
    keys = ('return', 'throw', 'case', 'typeof', 'void', 'delete', 'do', 'in', 'of', 'instanceof', 'yield', 'await', 'else', 'new', 'extends')
    def walk(s):
        out = []; i = 0; n = len(s)
        while i < n:
            c = s[i]
            if c in ' \t':
                while i < n and s[i] in ' \t': i += 1
                prev = out[-1] if out else ''; nxt = s[i] if i < n else ''
                if prev in punct or nxt in punct: continue
                out.append(' '); continue
            if c in '\'"`':
                q = c; out.append(c); i += 1
                while i < n:
                    ch = s[i]
                    if ch == '\\':
                        out.append(s[i:i + 2]); i += 2; continue
                    if q == '`' and ch == '$' and i + 1 < n and s[i + 1] == '{':
                        out.append('${'); i += 2; k = i; d = 1
                        while k < n and d:
                            ch2 = s[k]
                            if ch2 in '\'"`':
                                qq = ch2; k += 1
                                while k < n:
                                    if s[k] == '\\':
                                        k += 2; continue
                                    if qq == '`' and k + 1 < n and s[k] == '$' and s[k + 1] == '{':
                                        k += 2; dd = 1
                                        while k < n and dd:
                                            if s[k] == '{': dd += 1
                                            elif s[k] == '}': dd -= 1
                                            if s[k] == '\\':
                                                k += 2; continue
                                            k += 1
                                        continue
                                    if s[k] == qq:
                                        k += 1; break
                                    k += 1
                                continue
                            if ch2 == '{': d += 1
                            elif ch2 == '}': d -= 1
                            if d == 0: break
                            k += 1
                        out.append(walk(s[i:k])); out.append('}'); i = k + 1; continue
                    out.append(ch); i += 1
                    if ch == q: break
                continue
            if c == '/' and i + 1 < n and s[i + 1] == '/':
                j = s.find('\n', i)
                if j < 0: out.append(s[i:]); break
                out.append(s[i:j]); i = j; continue
            if c == '/' and i + 1 < n and s[i + 1] == '*':
                j = s.find('*/', i + 2)
                if j < 0: out.append(s[i:]); break
                out.append(s[i:j + 2]); i = j + 2; continue
            if c == '/':
                prev = ''.join(out).rstrip(' \t'); is_re = not prev or prev[-1] in re_prev
                if not is_re:
                    for k in keys:
                        if prev.endswith(k) and (len(prev) == len(k) or not (prev[-len(k) - 1].isalnum() or prev[-len(k) - 1] in '_$')):
                            is_re = True; break
                if is_re:
                    out.append(c); i += 1; in_class = False
                    while i < n:
                        ch = s[i]
                        if ch == '\\':
                            out.append(s[i:i + 2]); i += 2; continue
                        out.append(ch); i += 1
                        if ch == '[' and not in_class: in_class = True; continue
                        if ch == ']' and in_class: in_class = False; continue
                        if ch == '/' and not in_class:
                            while i < n and (s[i].isalnum() or s[i] == '_'):
                                out.append(s[i]); i += 1
                            break
                        if ch == '\n': break
                    continue
            out.append(c); i += 1
        return ''.join(out)
    return walk(src)
def slim(m, s):
    # single-file only: the registry's provenance 'source' strings are not read by any UI (the site copy keeps them)
    if m == 'src/req_packet.js':
        # 4.9.167: auditCard uses id + test ids only; drop statement/falsify and long L() names so gzip leave ≥5 kB (Pages keeps full packet)
        s = re.sub(r"statement:\s*'([^'\\]|\\.)*'", "statement:''", s)
        s = re.sub(r"falsify:\s*'([^'\\]|\\.)*'", "falsify:''", s)
        s = re.sub(r"L\(('(?:[^'\\]|\\.)*'),\s*('(?:[^'\\]|\\.)*'),\s*('(?:[^'\\]|\\.)*'),\s*'(?:[^'\\]|\\.)*',", r"L(\1, \2, \3, '',", s)
        return s
    if m == 'src/release.js':
        # 4.9.169: the operator panel prints sha256.slice(0, 16). The single file stores that prefix. Pages keeps the full hash.
        a = s.index('const d = ') + 10; b = s.rindex('; if (typeof module'); d = json.loads(s[a:b])
        for f in d.get('files') or []:
            hsh = f.get('sha256')
            if isinstance(hsh, str) and len(hsh) > 16: f['sha256'] = hsh[:16]
        return s[:a] + json.dumps(d, separators=(',', ':'), ensure_ascii=False) + s[b:]
    if m != 'src/features.js': return s
    a = s.index('const d = ') + 10; b = s.rindex('; if (typeof module'); d = json.loads(s[a:b])
    # 4.9.87–4.9.164: omit note/wave/name for kernel-app.html gzip; Pages keeps full registry.
    # 4.9.167: also omit proof arrays (claim table keeps id/status; Pages keeps proofs) so leave ≥5 kB under 570 kB.
    # 4.9.169: proofs are already omitted, so the suite pass map is unused here. Pages keeps suites.
    for f in d.get('features', []):
        f.pop('source', None); f.pop('note', None); f.pop('wave', None)
        f.pop('name', None)
        f.pop('proof', None)
    d.pop('generated', None); d.pop('gate', None); d.pop('suites', None)
    return s[:a] + json.dumps(d, separators=(',', ':'), ensure_ascii=False) + s[b:]
